#!/usr/bin/env bash
# Regenerates docs/THIRD-PARTY-LICENSES.md from the resolved SwiftPM checkouts.
#
# MIT (Sparkle), BSD-3-Clause (LevelDB) and zlib (nanopb, ed25519) all require their
# notice to accompany binary distributions, so the text has to live in the repo rather
# than be linked. Apache-2.0 components are included for completeness.
#
# Needs the packages resolved once (make build, or any xcodebuild run) so the checkouts
# exist. Run after bumping a dependency in project.yml.
set -euo pipefail
cd "$(dirname "$0")/.."

CK=$(find build -type d -path "*SourcePackages/checkouts" -print -quit 2>/dev/null || true)
if [ -z "$CK" ] || [ ! -d "$CK" ]; then
  echo "error: no SwiftPM checkouts found under build/. Run 'make build' first." >&2
  exit 1
fi
OUT=docs/THIRD-PARTY-LICENSES.md

emit() { # name, spdx, license-file, upstream-url
  local name=$1 spdx=$2 path=$3 url=$4
  if [ ! -f "$path" ]; then
    echo "error: missing licence file for $name: $path" >&2
    exit 1
  fi
  printf '## %s — %s\n\nSource: %s\n\n```text\n' "$name" "$spdx" "$url"
  cat "$path"
  printf '```\n\n'
}

{
  cat <<HDR
# Third-party licences

DiskGarden redistributes the components below. This file reproduces their licence
text verbatim, as MIT, BSD-3-Clause and zlib all require the notice to accompany
binary distributions.

Generated by scripts/gen-third-party-licenses.sh — do not edit by hand. See \`NOTICE\`
for the summary and
\`DiskGarden.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved\`
for the pinned versions. Regenerate with \`make third-party-licenses\`.

HDR
  emit "Sparkle" "MIT" "$CK/Sparkle/LICENSE" "https://github.com/sparkle-project/Sparkle"
  emit "ed25519 (vendored by Sparkle)" "zlib" "$CK/Sparkle/Vendor/ed25519-sparkle/license.txt" "https://github.com/orlp/ed25519"
  emit "Firebase Apple SDK" "Apache-2.0" "$CK/firebase-ios-sdk/LICENSE" "https://github.com/firebase/firebase-ios-sdk"
  emit "GoogleUtilities" "Apache-2.0" "$CK/GoogleUtilities/LICENSE" "https://github.com/google/GoogleUtilities"
  emit "GoogleDataTransport" "Apache-2.0" "$CK/GoogleDataTransport/LICENSE" "https://github.com/google/GoogleDataTransport"
  emit "Promises" "Apache-2.0" "$CK/promises/LICENSE" "https://github.com/google/promises"
  emit "gRPC (binary distribution)" "Apache-2.0" "$CK/grpc-binary/LICENSE" "https://github.com/google/grpc-binary"
  emit "Abseil-C++ (binary distribution)" "Apache-2.0" "$CK/abseil-cpp-binary/LICENSE" "https://github.com/google/abseil-cpp-binary"
  emit "app-check" "Apache-2.0" "$CK/app-check/LICENSE" "https://github.com/google/app-check"
  emit "interop-ios-for-google-sdks" "Apache-2.0" "$CK/interop-ios-for-google-sdks/LICENSE" "https://github.com/google/interop-ios-for-google-sdks"
  emit "LevelDB" "BSD-3-Clause" "$CK/leveldb/LICENSE" "https://github.com/firebase/leveldb"
  emit "nanopb" "zlib" "$CK/nanopb/LICENSE.txt" "https://github.com/firebase/nanopb"
} > "$OUT"

echo "wrote $OUT ($(grep -c '^## ' "$OUT") components, from $CK)"
